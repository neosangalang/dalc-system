    <section id="human-in-the-loop">
        <h2><i class="fa fa-user-check text-[#10B981]"></i> 3. Mandatory Human-in-the-Loop (HITL) Verification</h2>
        <p>
            DALC operates under a strict <strong>Zero Autonomous Publishing</strong> policy:
        </p>
        <ul>
            <li><strong>Editable Draft State:</strong> All AI outputs populate editable text areas within the educator's active interface. No AI-generated content is automatically committed to the student's permanent record.</li>
            <li><strong>Mandatory Educator Review:</strong> Educators must thoroughly review, verify accuracy against observed reality, edit nuances, and personally endorse every record before clicking "Save".</li>
            <li><strong>Administrative Approval Gate:</strong> Official Quarterly Progress Reports undergo an additional administrative approval workflow (`can_approve_reports`) before being published to guardians.</li>
            <li><strong>Accountability:</strong> The educator who validates and commits the documentation remains wholly professional and legally accountable for the finalized record.</li>
        </ul>
    </section>

    <section id="pii-sanitization">
        <h2><i class="fa fa-user-shield text-[#3B82F6]"></i> 4. Privacy & Zero-PII Prompt Sanitization</h2>
        <p>
            To protect student privacy and comply with the Philippine <em>Data Privacy Act of 2012</em>, all communication with the AI inference endpoint executes through a private, server-side Laravel proxy:
        </p>
        <ul>
            <li><strong>Excluded Sensitive Fields:</strong> Prompts dispatched to Groq Cloud strictly omit the student's Learner Reference Number (LRN), surname, guardian contact info, home address, and external clinical identifiers.</li>
            <li><strong>Contextual Anonymization:</strong> Prompts pass only the student's first name, age, developmental domain, and teacher's raw pedagogical observation text.</li>
            <li><strong>Zero Training Retention:</strong> Enterprise API terms ensure that prompt payloads are not cached, persisted, or utilized to train future public foundational models.</li>
            <li><strong>API Key Isolation:</strong> All AI credentials (`GROQ_API_KEY`) reside exclusively in encrypted server environment files, completely shielded from client-side inspection.</li>
        </ul>
    </section>

    <section id="iep-generation">
        <h2><i class="fa fa-bullseye text-[#C4922E]"></i> 5. IEP SMART Goal Synthesis Standards</h2>
        <p>
            When synthesizing Individualized Education Programs, the AI assistant adheres to rigorous SPED prompt engineering constraints:
        </p>
        <ul>
            <li><strong>SMART Criteria:</strong> Goals must be Specific, Measurable, Attainable, Relevant, and Time-bound within a 36-week academic cycle.</li>
            <li><strong>Multi-Domain Coverage:</strong> Formulations address Cognitive, Receptive & Expressive Communication, Gross & Fine Motor, Social-Emotional, and Adaptive Behavior domains.</li>
            <li><strong>Baseline Verification:</strong> Goals must reference observed baseline performance (PLOP) rather than generic grade-level expectations.</li>
        </ul>
    </section>

    <section id="home-activities">
        <h2><i class="fa fa-house-chimney text-[#10B981]"></i> 6. Home Learning Activities Guidance</h2>
        <p>
            AI-suggested home activities provided to parents are framed by strict safety and pedagogical rules:
        </p>
        <ul>
            <li><strong>Safe & Everyday Materials:</strong> Suggestions only incorporate standard household objects (e.g., cups, pillows, cushions, picture books) and strictly avoid specialized clinical gear.</li>
            <li><strong>Parent-Friendly & Empathetic Tone:</strong> Language is free of clinical jargon and designed to encourage positive bonding without placing emotional stress on the family.</li>
            <li><strong>Voluntary Nature:</strong> Home activities are suggested supplementary exercises, not mandatory academic prerequisites.</li>
        </ul>
    </section>

    <section id="teacher-obligations">
        <h2><i class="fa fa-award text-[#1E2657]"></i> 7. Educator Ethical Obligations & Prohibited AI Conduct</h2>
        <p>
            All DALC educators, therapists, and staff agree to the following ethical tenets:
        </p>
        <ol>
            <li><strong>Never copy-paste unedited AI output</strong> without reading and confirming that the clinical description accurately reflects the child's true classroom demeanor.</li>
            <li><strong>Never input private parent-teacher communications</strong> or external family disputes into AI prompt textboxes.</li>
            <li><strong>Always override AI suggestions</strong> whenever the model fails to capture sensory accommodations or behavioral nuances unique to the child.</li>
        </ol>
