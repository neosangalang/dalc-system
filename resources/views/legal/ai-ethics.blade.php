        <h2><i class="fa fa-microchip text-[#4F6AF5]"></i> 1. Purpose & Architecture Overview</h2>
        <p>
            Dream Achievers Learning Center integrates high-throughput, low-latency AI inference powered by <strong>Groq Cloud</strong> (`openai/gpt-oss-20b`) to alleviate educator administrative burden and elevate documentation quality across four core workflows:
        </p>
        <ol>
            <li><strong>Daily Observation Log Rewriting:</strong> Translates rapid, informal teacher bullet points into clinically structured, objective, and strengths-focused documentation.</li>
            <li><strong>IEP SMART Goal Synthesis:</strong> Derives measurable 36-week benchmarks, quarterly milestones, and classroom accommodations from Present Level of Performance (PLOP) baselines.</li>
            <li><strong>Quarterly Progress Report Drafting:</strong> Synthesizes quarterly daily logs and IEP ratings into comprehensive developmental narrative drafts.</li>
            <li><strong>Home Learning Recommendations:</strong> Formulates gentle, parent-friendly home activities to reinforce classroom developmental gains.</li>
        </ol>
    </section>

